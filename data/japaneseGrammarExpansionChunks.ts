export const JAPANESE_GRAMMAR_EXPANSION_CHUNKS: JapaneseChunkLesson[] = seeds.map((seed, index) => {
  const answer = index % 3;
  const listeningAnswer = (index + 2) % 3;
  const blankAnswer = (index + 1) % 3;
  const choicesAt = (correct: string, wrong: [string, string], position: number): string[] => {
    const choices = [...wrong];
    choices.splice(position, 0, correct);
    return choices;
  };
  const lessonId = `grammar:${seed.id}`;
  return {
    lessonId,
    expression: seed.expression,
    sentence: seed.sentence,
    meaning: seed.meaning,
    chunks: seed.chunks,
    variations: seed.variations,
    questions: [
      { id: `${lessonId}-chunk-meaning`, kind: 'meaning', prompt: `「${seed.sentence}」의 뜻을 골라요.`, choices: choicesAt(seed.meaning, seed.wrongMeanings, answer), answer, explanation: seed.explanation },
      { id: `${lessonId}-chunk-blank`, kind: 'blank', prompt: seed.blank.prompt, choices: choicesAt(seed.blank.correct, seed.blank.wrong, blankAnswer), answer: blankAnswer, explanation: seed.blank.explanation },
      { id: `${lessonId}-chunk-listening`, kind: 'listening', prompt: '문장을 듣고 뜻을 골라요.', choices: choicesAt(seed.meaning, seed.wrongMeanings, listeningAnswer), answer: listeningAnswer, explanation: seed.explanation, audioText: seed.sentence },
    ],
  };
});
