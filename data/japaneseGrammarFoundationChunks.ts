import type { JapaneseChunkLesson } from './japaneseChunkLessons.ts';

// Each boundary, variation and distractor is authored for this grammar point.
// The helper only packages these curated values into the shared practice contract.
type Chunk = [text: string, meaning: string, role: string];
type Variation = [kind: 'word' | 'tense', label: string, sentence: string, meaning: string, explanation: string];
type Entry = {
  id: string; expression: string; sentence: string; meaning: string;
  chunks: Chunk[]; variations: [Variation, Variation];
  wrongMeanings: [string, string]; blank: string; choices: [string, string, string];
  answer: number; explanation: string;
};
function lesson(entry: Entry, index: number): JapaneseChunkLesson {
  const lessonId = `grammar:${entry.id}`;
  const meaningAnswer = index % 3;
  const meaningChoices = [...entry.wrongMeanings];
  meaningChoices.splice(meaningAnswer, 0, entry.meaning);
  const listeningChoices = [meaningChoices[2], meaningChoices[0], meaningChoices[1]];
  return {
    lessonId, expression: entry.expression, sentence: entry.sentence, meaning: entry.meaning,
    chunks: entry.chunks.map(([text, meaning, role]) => ({ text, meaning, role })),
    variations: entry.variations.map(([kind, label, sentence, meaning, explanation]) => ({ kind, label, sentence, meaning, explanation })),
    questions: [
      { id: `${lessonId}:meaning`, kind: 'meaning', prompt: `「${entry.sentence}」의 뜻은?`, choices: meaningChoices, answer: meaningAnswer, explanation: entry.explanation },
      { id: `${lessonId}:blank`, kind: 'blank', prompt: entry.blank, choices: entry.choices, answer: entry.answer, explanation: entry.explanation },
      { id: `${lessonId}:listening`, kind: 'listening', prompt: '문장을 듣고 알맞은 한국어 뜻을 고르세요.', audioText: entry.sentence, choices: listeningChoices, answer: (meaningAnswer + 1) % 3, explanation: entry.explanation },
    ],
  };
}

